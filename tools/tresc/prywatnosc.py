def akapit(tekst):
    return '<!-- wp:paragraph -->\n<p>%s</p>\n<!-- /wp:paragraph -->' % tekst


def punkt(tresc, podpunkty=None):
    srodek = '<li>%s' % tresc
    if podpunkty:
        srodek += '\n<!-- wp:list -->\n<ul class="wp-block-list">\n%s\n</ul>\n<!-- /wp:list -->' % (
            '\n'.join('<!-- wp:list-item -->\n<li>%s</li>\n<!-- /wp:list-item -->' % p
                      for p in podpunkty))
    return '<!-- wp:list-item -->\n%s</li>\n<!-- /wp:list-item -->' % srodek


def zbuduj():
    czesci = []

    for tytul, rodzaj, pozycje in SEKCJE:
        czesci.append(
            '<!-- wp:heading -->\n<h2 class="wp-block-heading">%s</h2>\n<!-- /wp:heading -->' % tytul)

        bufor = []

        def zamknij():
            if not bufor:
                return
            znacznik = 'ol' if rodzaj == 'ol' else 'ul'
            glowa = '<!-- wp:list {"ordered":true} -->' if rodzaj == 'ol' else '<!-- wp:list -->'
            czesci.append('%s\n<%s class="wp-block-list">\n%s\n</%s>\n<!-- /wp:list -->'
                          % (glowa, znacznik, '\n'.join(bufor), znacznik))
            bufor.clear()

        for poz in pozycje:
            # Prefiks "__" znaczy akapit wprowadzający albo domykający, a nie punkt listy.
            if isinstance(poz, str) and poz.startswith('__'):
                zamknij()
                czesci.append(akapit(poz[2:]))
                continue

            if isinstance(poz, tuple):
                bufor.append(punkt(poz[0], poz[1]))
            else:
                bufor.append(punkt(poz))

        zamknij()

    glowa = ('<!-- wp:ntc/prose {"label":"RODO",'
             '"title":"Polityka Prywatności NTC ANDAR Sp. z o.o.",'
             '"lead":"%s"} -->' % LEAD)

    return '%s\n%s\n<!-- /wp:ntc/prose -->' % (glowa, '\n'.join(czesci))
